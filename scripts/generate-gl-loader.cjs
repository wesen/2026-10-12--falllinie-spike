const fs=require('node:fs');const path=require('node:path');
const root=path.resolve(__dirname,'..');
const names=new Set();
for(const file of fs.readdirSync(path.join(root,'src')).filter(x=>x.endsWith('.cpp'))) {
 const text=fs.readFileSync(path.join(root,'src',file),'utf8');
 for(const m of text.matchAll(/\b(gl[A-Z]\w*)\s*\(/g))names.add(m[1]);
}
const functions=[...names].sort();
let out='// Generated by scripts/generate-gl-loader.cjs; do not edit.\n#pragma once\n#include <SDL.h>\n#include <GLES3/gl3.h>\n#include <stdexcept>\n#include <string>\nnamespace glapi {\n';
for(const n of functions)out+=`inline decltype(&::${n}) ${n}_fn = nullptr;\n`;
out+='inline void load() {\n';
for(const n of functions)out+=`  ${n}_fn = reinterpret_cast<decltype(${n}_fn)>(SDL_GL_GetProcAddress("${n}"));\n  if (!${n}_fn) throw std::runtime_error("missing GL entry: ${n}");\n`;
out+='}\n}\n';
for(const n of functions)out+=`#define ${n} glapi::${n}_fn\n`;
fs.writeFileSync(path.join(root,'src/gl_api.hpp'),out);
console.log('Generated '+functions.length+' GL entry points');
